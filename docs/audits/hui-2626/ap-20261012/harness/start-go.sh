#!/bin/bash
# HUI-2626 盲评修复复录（2026-10-12）本地链启动。测试值全部走环境变量注入，不入仓。
# 前置：source walk.env（LEADS_WALK_* 六个值）；LEADS_WALK_HOME=scratchpad 根；
# 二进制 $LEADS_WALK_HOME/leads-server 由本工作树 server/ 构建；租户已 provision 并
# 导出 LEADS_WALK_TENANT_A / LEADS_WALK_TENANT_B。
set -eu
: "${LEADS_WALK_HOME:?need LEADS_WALK_HOME}"
: "${LEADS_WALK_INTERNAL_TOKEN:?}" "${LEADS_WALK_IDENTITY_TOKEN:?}" "${LEADS_WALK_TOUCH_SECRET:?}"
: "${LEADS_WALK_FETCH_TOKEN:?}" "${LEADS_WALK_PEPPER:?}" "${LEADS_WALK_DEDUP:?}"
: "${LEADS_WALK_TENANT_A:?}" "${LEADS_WALK_TENANT_B:?}"
P=$(lsof -ti tcp:29300 -sTCP:LISTEN || true); if [ -n "$P" ]; then kill $P; sleep 1; fi
env LEADS_HTTP_ADDR=127.0.0.1:29300 \
  LEADS_DB_PATH="$LEADS_WALK_HOME/leads.db" \
  LEADS_INTERNAL_TOKEN="$LEADS_WALK_INTERNAL_TOKEN" \
  PLATFORM_IDENTITY_BASE_URL=http://127.0.0.1:29310 PLATFORM_IDENTITY_TOKEN="$LEADS_WALK_IDENTITY_TOKEN" \
  LEADS_APP_ID=leads RECEPTION_VISITOR_PEPPER="$LEADS_WALK_PEPPER" LEADS_DEDUP_PEPPER="$LEADS_WALK_DEDUP" \
  FEATURE_FOLLOWUPS=true FEATURE_LEADS_ASSIGN=true FEATURE_LEADS_FILTER=true FEATURE_RECEPTION=true FEATURE_FUNNEL=true \
  FEATURE_CONTACT_TAGS=true FEATURE_SERVICE_DRAFT=true FEATURE_LIGHT_COPY=true FEATURE_CHANNEL_ANALYTICS=true FEATURE_INTENT_GRADE=true \
  FEATURE_NOTIFY_INGEST=true LEADS_INGEST_SOURCES=touch-engine LEADS_INGEST_TOUCH_ENGINE_SECRET="$LEADS_WALK_TOUCH_SECRET" \
  LEADS_INGEST_TOUCH_ENGINE_FETCH_BASE=http://127.0.0.1:29320 LEADS_INGEST_TOUCH_ENGINE_FETCH_TOKEN="$LEADS_WALK_FETCH_TOKEN" \
  LEADS_TENANT_BINDINGS="touch-engine/notify/touch_t_a=${LEADS_WALK_TENANT_A}@1,touch-engine/notify/touch_t_b=${LEADS_WALK_TENANT_B}@1" \
  nohup "$LEADS_WALK_HOME/leads-server" > "$LEADS_WALK_HOME/server.log" 2>&1 &
echo "leads-server starting on 29300 (log: $LEADS_WALK_HOME/server.log)"
